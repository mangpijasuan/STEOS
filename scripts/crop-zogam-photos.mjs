const [out, ...pages] = process.argv.slice(2);
if (!out || pages.length !== groups.length) throw new Error("Provide a fresh output directory and six page paths in the documented order.");
const dims = pages.map(p => execFileSync("magick", [p, "-auto-orient", "-format", "%w %h", "info:"], {encoding:"utf8"}).trim());
if (dims.some(d => d !== "1275 1650")) throw new Error("Expected all six original pages to be 1275 x 1650; got " + dims.join(", "));
mkdirSync(out);
for (const [i, [category, crops]] of groups.entries()) {
  for (const [name, x, y, right, bottom] of crops) {
    execFileSync("magick", [pages[i], "-auto-orient", "-crop", `${right-x}x${bottom-y}+${x}+${y}`, "+repage",
      "-colorspace", "sRGB", "-unsharp", "0x0.6+0.5+0.02", "-strip", "-quality", "90", join(out, name + ".jpg")]);
    console.log(category + ": " + name);
  }
}
